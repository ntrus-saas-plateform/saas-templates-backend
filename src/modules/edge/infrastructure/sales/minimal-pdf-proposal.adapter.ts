import { Injectable } from '@nestjs/common';
import type {
  ProposalDocumentInput,
  ProposalDocumentResult,
  SalesProposalDocumentAdapterPort,
} from '../../domain/sales/proposal-document.adapter.port.js';

/**
 * Generates a minimal valid PDF without external libraries.
 * Honest artifact for proposals — not a design-studio renderer.
 */
@Injectable()
export class MinimalPdfProposalAdapter implements SalesProposalDocumentAdapterPort {
  async generate(input: ProposalDocumentInput): Promise<ProposalDocumentResult> {
    const lines = [
      input.title,
      `Proposal ${input.proposalNumber}`,
      `Language: ${input.language}`,
      '',
      ...input.sections.flatMap((s) => [
        s.title ?? s.code ?? 'Section',
        s.body ?? '',
        '',
      ]),
      'Generated by Okapi Edge Sales — capabilities limited to approved commercial data.',
    ];
    const content = lines.join('\n');
    const pdf = buildMinimalPdf(content);
    const bytesBase64 = Buffer.from(pdf, 'binary').toString('base64');
    return {
      outcome: 'GENERATED',
      format: 'application/pdf',
      documentRef: `sales://proposals/${input.proposalId}.pdf`,
      bytesBase64,
    };
  }
}

function buildMinimalPdf(text: string): string {
  const escaped = text
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .slice(0, 3500);
  const stream = `BT /F1 10 Tf 50 750 Td 14 TL (${escaped.replace(/\n/g, ') Tj T* (')}) Tj ET`;
  const objects = [
    '1 0 obj<< /Type /Catalog /Pages 2 0 R >>endobj\n',
    '2 0 obj<< /Type /Pages /Kids [3 0 R] /Count 1 >>endobj\n',
    '3 0 obj<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources<< /Font<< /F1 5 0 R >> >> >>endobj\n',
    `4 0 obj<< /Length ${stream.length} >>stream\n${stream}\nendstream\nendobj\n`,
    '5 0 obj<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>endobj\n',
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (const obj of objects) {
    offsets.push(Buffer.byteLength(pdf, 'binary'));
    pdf += obj;
  }
  const xrefStart = Buffer.byteLength(pdf, 'binary');
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let i = 1; i < offsets.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;
  return pdf;
}
